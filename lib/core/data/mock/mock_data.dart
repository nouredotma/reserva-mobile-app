String _reviewCategoryForId(String id) {
  if (id.startsWith('svc')) return 'services';
  if (id.startsWith('h')) return 'voyage';
  if (id.startsWith('r')) return 'restaurants';
  if (id.startsWith('s')) return 'wellness';
  if (id.startsWith('dp')) return 'day-passes';
  if (id.startsWith('ev')) return 'spectacles';
  if (id.startsWith('vip')) return 'conciergerie';
  if (id.startsWith('corp')) return 'corporate';
  return 'voyage';
}

int _digits(String id) {
  final match = RegExp(r'\d+').firstMatch(id);
  return match == null ? 0 : int.parse(match.group(0)!);
}

